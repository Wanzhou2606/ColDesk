/** 紧凑打卡页实机检查，不使用用户数据库。 */
const { app, BrowserWindow, nativeTheme } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const output = path.resolve(__dirname, '../preview/habits-check');
fs.mkdirSync(output, { recursive: true });
app.setPath('userData', fs.mkdtempSync(path.join(output, 'data-')));
app.setLoginItemSettings = () => {};
app.getLoginItemSettings = () => ({ openAtLogin: false });
process.env.COLDESK_SEED_SAMPLE = '1';
process.env.COLDESK_DISABLE_SCHEDULER = '1';
nativeTheme.themeSource = 'light';
require(path.resolve(__dirname, '../out/main/index.cjs'));
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
const assert = (ok, message) => { if(!ok)throw new Error(message); };
const waitFor = async (fn, message) => { for(let i=0;i<50;i++){if(await fn())return;await delay(100);}throw new Error(message); };
(async () => {
  let main;
  try {
    await app.whenReady(); await delay(2200);
    main = BrowserWindow.getAllWindows().find(w => w.getTitle() === 'ColDesk');
    const js = code => main.webContents.executeJavaScript(code);
    const capture = async name => fs.writeFileSync(path.join(output,name+'.png'),(await main.capturePage()).toPNG());
    await js(`window.coldesk.invoke('settings:update',{onboardingVersion:1})`);
    await js(`Array.from(document.querySelectorAll('.nav-item')).find(b=>b.textContent.trim()==='打卡').click()`);
    await waitFor(()=>js(`!!document.querySelector('.habits-layout')`),'打卡页未加载');
    await delay(250);
    const inspect = () => js(`(() => { const content=document.querySelector('.content'), calendar=document.querySelector('.habit-calendar'), panel=document.querySelector('.habit-calendar-panel'), input=document.querySelector('input[aria-label="新习惯名"]');return {width:innerWidth,height:innerHeight,pageWidth:content.clientWidth,pageScrollWidth:content.scrollWidth,calendarHeight:calendar.getBoundingClientRect().height,calendarPanelHeight:panel.getBoundingClientRect().height,calendarPanelWidth:panel.getBoundingClientRect().width,dayHeight:document.querySelector('.habit-day').getBoundingClientRect().height,inputBottom:input.getBoundingClientRect().bottom}; })()`);
    const report = { normal: await inspect() };
    assert(report.normal.calendarHeight < 250,'月历仍然过高');
    assert(report.normal.dayHeight <= 34,'日期格没有缩小');
    assert(report.normal.calendarPanelWidth <= 321,'月历仍占整页宽度');
    assert(report.normal.inputBottom <= report.normal.height,'新增习惯入口在默认窗口不可见');
    await capture('habits');
    const month = await js(`window.coldesk.invoke('state:get').then(s=>s.habit.month)`);
    await js(`document.querySelector('button[title="上个月"]').click()`);
    await waitFor(()=>js(`window.coldesk.invoke('state:get').then(s=>s.habit.month!==${JSON.stringify(month)})`),'翻月失效');
    await js(`document.querySelector('button[title="回到本月"]').click()`);
    await waitFor(()=>js(`window.coldesk.invoke('state:get').then(s=>s.habit.month===${JSON.stringify(month)})`),'回到本月失效');
    const before = await js(`document.querySelector('.habit-check').getAttribute('aria-pressed')`);
    await js(`document.querySelector('.habit-check').click()`);
    await waitFor(()=>js(`document.querySelector('.habit-check').getAttribute('aria-pressed')!==${JSON.stringify(before)}`),'打卡未生效');
    await js(`document.querySelector('.habit-check').click()`);
    await waitFor(()=>js(`document.querySelector('.habit-check').getAttribute('aria-pressed')===${JSON.stringify(before)}`),'取消打卡未生效');
    await js(`document.querySelector('.page-head .primary-btn').click()`);
    assert(await js(`document.activeElement===document.querySelector('input[aria-label="新习惯名"]')`),'新建习惯按钮没有定位输入框');
    await js(`(() => { const input=document.activeElement;Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'坚持阅读');input.dispatchEvent(new Event('input',{bubbles:true})); })()`);
    await delay(100);
    await js(`document.querySelector('.habit-manage-panel .budget-total-row button').click()`);
    await waitFor(()=>js(`window.coldesk.invoke('state:get').then(s=>s.habit.habits.some(h=>h.name==='坚持阅读'))`),'新增习惯失败');
    await js(`document.querySelector('.habit-manage-toggle').click()`); await delay(150);
    assert(await js(`document.querySelector('.habit-list').textContent.includes('坚持阅读')`),'管理列表未显示新增习惯');
    await js(`document.querySelector('.habit-manage-toggle').click()`); await delay(150);
    main.setSize(900,600); await delay(250);
    await js(`document.querySelector('.content').scrollTop=0`);
    report.narrow = await inspect();
    assert(report.narrow.pageScrollWidth <= report.narrow.pageWidth+1,'小窗口出现横向溢出');
    assert(report.narrow.inputBottom <= report.narrow.height,'小窗口新增入口被挤到视野之外');
    await capture('habits-narrow');
    await js(`window.coldesk.invoke('habit:setMonth',{month:'2026-08'})`);
    await delay(200);
    report.sixWeeks = await inspect();
    assert(report.sixWeeks.calendarHeight < 250,'六行月份过高');
    await capture('habits-six-weeks');
    main.setSize(1120,760); nativeTheme.themeSource='dark'; await delay(250);
    await capture('habits-dark');
    report.checkin = true; report.monthNavigation = true; report.addHabit = true;
    fs.writeFileSync(path.join(output,'report.json'),JSON.stringify(report,null,2));
    console.log(JSON.stringify({ok:true,...report},null,2)); app.quit();
  } catch(error) { if(main&&!main.isDestroyed())fs.writeFileSync(path.join(output,'failure.png'),(await main.capturePage()).toPNG());console.error(error);app.exit(1); }
})();
