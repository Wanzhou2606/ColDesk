/** 首次使用完整流程，隔离数据库；--resume 验证真正重启后的状态。 */
const { app, BrowserWindow, ipcMain, nativeTheme } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const output = path.resolve(__dirname, '../preview/onboarding-check');
fs.mkdirSync(output, { recursive: true });
const resume = process.argv.includes('--resume');
const dataPath = resume ? fs.readFileSync(path.join(output, 'data-path.txt'), 'utf8') : fs.mkdtempSync(path.join(output, 'data-'));
if (!path.resolve(dataPath).startsWith(output + path.sep)) throw new Error('测试数据必须位于测试目录');
if (!resume) fs.writeFileSync(path.join(output, 'data-path.txt'), dataPath);
app.setPath('userData', dataPath);
app.requestSingleInstanceLock = () => true;
app.setLoginItemSettings = () => {};
app.getLoginItemSettings = () => ({ openAtLogin: false });
delete process.env.COLDESK_SEED_SAMPLE;
process.env.COLDESK_DISABLE_SCHEDULER = '1';
nativeTheme.themeSource = 'light';
let failCreate = !resume;
const handle = ipcMain.handle.bind(ipcMain);
ipcMain.handle = (channel, handler) => handle(channel, (...args) => {
  if (channel === 'task:create' && failCreate) { failCreate = false; throw new Error('SQLITE_ERROR: 模拟内部保存失败'); }
  return handler(...args);
});
require(path.resolve(__dirname, '../out/main/index.cjs'));
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
const assert = (ok, message) => { if(!ok)throw new Error(message); };
const waitFor = async (fn, message) => { for(let i=0;i<70;i++){ if(await fn())return; await delay(100); } throw new Error(message); };
(async () => {
  let main;
  try {
    await app.whenReady(); await delay(1800);
    main = BrowserWindow.getAllWindows().find(w => w.getTitle() === 'ColDesk');
    main.setTitle('ColDesk · 教程检查');
    const js = code => main.webContents.executeJavaScript(code);
    const state = () => js(`window.coldesk.invoke('state:get')`);
    const capture = async name => { await delay(180); fs.writeFileSync(path.join(output, name + '.png'), (await main.capturePage()).toPNG()); };
    const click = async (selector, text) => {
      await js(`Array.from(document.querySelectorAll(${JSON.stringify(selector)})).find(b=>b.textContent.trim()===${JSON.stringify(text)}).click()`);
      await delay(150);
    };
    await waitFor(() => js(`!!document.querySelector('.app')`), '主界面未加载');
    if(resume) {
      const saved = await state();
      assert(saved.settings.onboardingVersion === 1, '引导完成状态没有持久化');
      assert(saved.settings.dailyDigestAt === '08:15', '引导选择未持久化');
      assert(saved.settings.highContrast === true, '高对比度未持久化');
      assert(!await js(`!!document.querySelector('[role="dialog"]')`), '完成引导后重启仍自动弹出');
      const tasks = await js(`window.coldesk.invoke('task:list')`);
      assert(tasks.filter(t=>t.title==='我的第一项任务').length === 1, '首项任务丢失或重复');
      fs.writeFileSync(path.join(output,'restart-report.json'),JSON.stringify({ok:true,taskCount:tasks.length,settings:saved.settings},null,2));
      console.log('重启验证通过：引导不再自动出现，设置与首项任务均保留');
      app.quit(); return;
    }
    const initial = await state();
    assert(initial.settings.onboardingVersion === 0, '新库已被误标为完成');
    assert((await js(`window.coldesk.invoke('task:list')`)).length === 0, '新库不应包含示例任务');
    assert(initial.courses.length === 0 && initial.expense.entries.length === 0 && initial.habit.habits.length === 0, '新库包含其他人的数据');
    assert(initial.expense.totalDailyBudget === 0, '未设置预算却存在预算');
    await waitFor(() => js(`document.querySelector('#intro-title')?.textContent==='欢迎使用 ColDesk'`), '首次引导没有打开');
    assert(await js(`['拖拽安排日程','home · 心灵田园','导出日记','字体与月历'].every(text=>document.querySelector('.intro-features').textContent.includes(text))`), '新功能未同步到教程');
    await capture('welcome');
    main.setSize(900,600); await delay(200);
    assert(await js(`(() => { const d=document.querySelector('.onboarding-dialog').getBoundingClientRect(), f=document.querySelector('.intro-footer').getBoundingClientRect(); return d.top>=0 && d.bottom<=innerHeight && f.bottom<=innerHeight && d.right<=innerWidth; })()`), '小窗口引导或按钮被裁切');
    await capture('welcome-narrow');
    nativeTheme.themeSource='dark'; await delay(200); await capture('welcome-dark');
    nativeTheme.themeSource='light'; main.setSize(1120,760); await delay(200);
    await click('.intro-footer button', '下一步');
    assert(await js(`document.querySelector('#intro-title').textContent==='按你的习惯设置'`), '未进入设置步骤');
    const setInput = async (selector, value) => js(`(() => { const input=document.querySelector(${JSON.stringify(selector)}); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,${JSON.stringify(value)}); input.dispatchEvent(new Event('input',{bubbles:true})); input.dispatchEvent(new Event('change',{bubbles:true})); })()`);
    await setInput('.intro-preferences input[type="time"]','08:15');
    await capture('preferences');
    await click('.intro-footer button', '下一步');
    await setInput('.intro-task input[maxlength]','我的第一项任务');
    const tomorrow = new Date(initial.date + 'T12:00'); tomorrow.setDate(tomorrow.getDate()+1);
    const due = `${tomorrow.getFullYear()}-${String(tomorrow.getMonth()+1).padStart(2,'0')}-${String(tomorrow.getDate()).padStart(2,'0')}T18:00`;
    await setInput('.intro-task input[type="datetime-local"]',due);
    await capture('first-task');
    await click('.intro-footer button', '下一步');
    assert(await js(`document.querySelector('.intro-replay')?.textContent.includes('设置 → 使用帮助 → 重新查看引导') && document.querySelector('.intro-replay')?.textContent.includes('三横杠')`), '最后一步缺少再次观看入口');
    main.setSize(900,600); await delay(150);
    await js(`document.querySelector('.intro-body').scrollTop=document.querySelector('.intro-body').scrollHeight`);
    assert(await js(`(()=>{const panel=document.querySelector('.intro-replay').getBoundingClientRect(), body=document.querySelector('.intro-body').getBoundingClientRect(), footer=document.querySelector('.intro-footer').getBoundingClientRect();return panel.top>=body.top && panel.bottom<=body.bottom+1 && footer.bottom<=innerHeight;})()`), '小窗口重看提示或操作按钮被裁切');
    await capture('ready-narrow'); main.setSize(1120,760); await delay(150);
    await capture('ready');
    await click('.intro-footer button', '开始使用');
    await waitFor(() => js(`!!document.querySelector('.intro-error')`), '模拟保存失败未显示提示');
    assert((await state()).settings.onboardingVersion === 0, '保存失败却标记引导完成');
    assert(!await js(`document.querySelector('.intro-error').textContent.includes('SQLITE')`), '内部错误泄漏到界面');
    await click('.intro-footer button', '开始使用');
    await waitFor(() => js(`!document.querySelector('[role="dialog"]')`), '保存成功后引导未关闭');
    const created = await js(`window.coldesk.invoke('task:list')`);
    assert(created.length===1 && created[0].title==='我的第一项任务', '首项任务不正确或重复');
    await capture('after-setup');
    await js(`document.querySelector('.settings-pill').click()`); await delay(150);
    await click('.settings-nav-item','?使用帮助');
    await waitFor(() => js(`!!document.querySelector('.help-grid')`),'帮助页未打开');
    await capture('help');
    await click('.help-welcome button','重新查看引导');
    await waitFor(() => js(`!!document.querySelector('[role="dialog"]')`),'引导无法重开');
    await click('.intro-footer button','关闭引导');
    assert((await js(`window.coldesk.invoke('task:list')`)).length===1,'重看引导产生重复任务');
    await click('.settings-nav-item','⚙通用');
    await js(`document.querySelectorAll('[role="switch"]')[1].click()`);
    await waitFor(() => js(`document.documentElement.dataset.contrast==='high'`),'高对比度没有生效');
    const widget = BrowserWindow.getAllWindows().find(w=>w.getTitle()==='ColDesk 悬浮窗');
    await waitFor(() => widget.webContents.executeJavaScript(`document.documentElement.dataset.contrast==='high'`),'高对比度未同步到浮窗');
    await click('.settings-nav-item','💾数据');
    assert(!await js(`document.body.innerText.includes('数据目录：') || document.body.innerText.includes('CSV / iCal')`),'仍显示内部路径或未实现功能');
    await capture('data-settings');
    await click('.settings-nav-item','ℹ关于');
    assert(!await js(`document.body.innerText.includes('当前校区：按设置')`),'仍显示占位文案');
    await capture('about');
    await js(`window.coldesk.invoke('widget:openExpenses')`); await delay(200);
    assert(await js(`document.body.innerText.includes('未设置预算')`),'记账空状态不清楚');
    await capture('empty-expenses');
    fs.writeFileSync(path.join(output,'report.json'),JSON.stringify({ok:true,freshData:true,taskCount:created.length,failedSaveRetry:true,replay:true,smallWindow:true,dark:true,settings:(await state()).settings},null,2));
    console.log('新用户流程验证通过：空数据、四步引导、失败重试、帮助重开与高对比度同步');
    app.quit();
  } catch(error) { if(main&&!main.isDestroyed())fs.writeFileSync(path.join(output,'failure.png'),(await main.capturePage()).toPNG()); console.error(error); app.exit(1); }
})();
