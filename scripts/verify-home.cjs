/** home 的真实窗口检查。独立数据库，--resume 检查密码和正文跨进程保存。 */
const { app, BrowserWindow, ipcMain, nativeTheme } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const output = path.resolve(__dirname, '../preview/home-check');
fs.mkdirSync(output, { recursive: true });
const resume = process.argv.includes('--resume');
const quitCheck = process.argv.includes('--quit-check');
const dataPath = (resume || quitCheck) ? fs.readFileSync(path.join(output,'data-path.txt'),'utf8') : fs.mkdtempSync(path.join(output,'data-'));
if (!path.resolve(dataPath).startsWith(output+path.sep)) throw new Error('测试目录异常');
if (!resume && !quitCheck)fs.writeFileSync(path.join(output,'data-path.txt'),dataPath);
app.setPath('userData',dataPath); app.setLoginItemSettings=()=>{};app.getLoginItemSettings=()=>({openAtLogin:false});
delete process.env.COLDESK_SEED_SAMPLE; process.env.COLDESK_DISABLE_SCHEDULER='1'; nativeTheme.themeSource='light';
let failNextSave = false;
const handle = ipcMain.handle.bind(ipcMain);
ipcMain.handle = (channel,listener) => handle(channel,(...args)=>{if(channel==='home:save' && failNextSave){failNextSave=false;throw new Error('模拟保存失败');}return listener(...args);});
require(path.resolve(__dirname,'../out/main/index.cjs'));
const delay=ms=>new Promise(r=>setTimeout(r,ms));
const assert=(ok,message)=>{if(!ok)throw new Error(message);};
const waitFor=async(fn,message)=>{for(let i=0;i<80;i++){if(await fn())return;await delay(100);}throw new Error(message);};
(async()=>{
  let main;
  try {
    await app.whenReady();await delay(1800);
    main=BrowserWindow.getAllWindows().find(w=>w.getTitle()==='ColDesk');
    let js=code=>main.webContents.executeJavaScript(code);
    const capture=async name=>{await delay(180);fs.writeFileSync(path.join(output,name+'.png'),(await main.capturePage()).toPNG());};
    const input=async(selector,value)=>js(`(()=>{const el=document.querySelector(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(el instanceof HTMLTextAreaElement?HTMLTextAreaElement.prototype:HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}));})()`);
    const clickText=async(selector,text)=>{await js(`Array.from(document.querySelectorAll(${JSON.stringify(selector)})).find(b=>b.textContent.trim()===${JSON.stringify(text)}).click()`);await delay(130);};
    const enter=async()=>{await clickText('.nav-item','home');await waitFor(()=>js(`!!document.querySelector('.home-page') && !document.body.innerText.includes('正在打开这片田园')`),'home 未打开');await delay(600);};
    await js(`window.coldesk.invoke('settings:update',{onboardingVersion:1})`);await delay(150);
    assert(await js(`document.querySelector('.page-title')?.textContent==='日程'`),'默认页面不再是日程');
    assert(await js(`document.querySelector('.nav-item .nav-label').textContent==='home'`),'home 不是第一项');
    const date=(resume||quitCheck)?fs.readFileSync(path.join(output,'entry-date.txt'),'utf8'):await js(`window.coldesk.invoke('state:get').then(s=>s.date)`);
    if (!resume && !quitCheck)fs.writeFileSync(path.join(output,'entry-date.txt'),date);
    await enter();
    if(resume||quitCheck){
      assert(await js(`!!document.querySelector('.home-unlock')`),'重启后未要求密码');
      assert(await js(`window.coldesk.invoke('home:month',{month:${JSON.stringify(date.slice(0,7))}}).then(()=>false,()=>true)`),'未解锁能读取封面');
      await input('.home-unlock input','garden-only-test');await clickText('.home-unlock .primary-btn','进入 home');
      await waitFor(()=>js(`!!document.querySelector('.home-month-grid')`),'重启后无法解锁');
      const saved=await js(`window.coldesk.invoke('home:get',{date:${JSON.stringify(date)}})`);
      assert(saved.cover==='今天给自己一点温柔。','重启后封面丢失');
      if(quitCheck){
        await js(`Array.from(document.querySelectorAll('.home-day')).find(b=>b.getAttribute('aria-label').startsWith(${JSON.stringify(date)})).click()`);
        await waitFor(()=>js(`!!document.querySelector('#home-body')`),'退出检查不能打开日记');
        await input('#home-body',saved.body+'\n直接退出前的最后一句。');
        await js(`window.coldesk.invoke('home:status')`);
        fs.writeFileSync(path.join(output,'quit-expected.txt'),'直接退出前的最后一句。');
        console.log('已写入未等待自动保存的内容，开始直接退出软件');
        app.quit();return;
      }      const expected=fs.existsSync(path.join(output,'quit-expected.txt'))?fs.readFileSync(path.join(output,'quit-expected.txt'),'utf8'):'窗口关闭前最后写下的一句话。';
      assert(saved.body.endsWith(expected),'关闭或退出软件前正文没有保存');
      fs.writeFileSync(path.join(output,'restart-report.json'),JSON.stringify({ok:true,date,protected:true,coverSaved:true,bodySaved:true},null,2));
      console.log('重启检查通过：默认日程、重新解锁、封面和正文保留');app.quit();return;
    }
    assert(await js(`document.body.innerText.includes('给心灵留一片田园')`),'未显示首次进入说明');await capture('welcome');
    await clickText('.home-gate-actions .primary-btn','进入 home');
    await waitFor(()=>js(`!!document.querySelector('.home-month-grid') && !document.querySelector('.home-month-grid').getAttribute('aria-busy').includes('true')`),'月历未加载');
    assert(await js(`document.querySelector('.sidebar').inert && document.querySelector('.sidebar').getBoundingClientRect().right<0`),'进入 home 导航未收起');
    await capture('calendar-empty');
    await js(`Array.from(document.querySelectorAll('.home-day')).find(b=>b.getAttribute('aria-label').startsWith(${JSON.stringify(date)})).click()`);
    await waitFor(()=>js(`!!document.querySelector('#home-cover')`),'日历日期不能进入日记');
    await input('#home-cover','今天给自己一点温柔。');await input('#home-body','今天慢下来，听到了风吹过树叶的声音。\n\n这是只属于自己的记录。');
    await js(`const w=document.querySelectorAll('.home-metadata select')[0];w.value='☀️ 晴天';w.dispatchEvent(new Event('change',{bubbles:true}));const m=document.querySelectorAll('.home-metadata select')[1];m.value='🌿 平静';m.dispatchEvent(new Event('change',{bubbles:true}));`);
    await capture('diary');
    // 等待前一次自动保存结束，再触发失败，确保失败停留在编辑器而不是误退。
    await delay(800);await input('#home-body','今天慢下来，听到了风吹过树叶的声音。\n\n这是只属于自己的记录。追加一句。');
    failNextSave=true;await clickText('.home-editor-foot button','保存并回到月历');
    await waitFor(()=>js(`!!document.querySelector('.home-error')`),'保存失败未显示提示');
    assert(await js(`!!document.querySelector('#home-body')`),'保存失败却退出编辑器');
    await clickText('.home-editor-foot button','保存并回到月历');
    await waitFor(()=>js(`!!document.querySelector('.home-month-grid') && document.querySelector('.home-month-grid').textContent.includes('今天给自己一点温柔。')`),'封面未回到月历');
    const entry=await js(`window.coldesk.invoke('home:get',{date:${JSON.stringify(date)}})`);
    assert(entry.weather==='☀️ 晴天'&&entry.mood==='🌿 平静','天气或心情未保存');
    assert(await js(`getComputedStyle(document.querySelector('.home-day.has-entry .home-cover')).fontFamily.includes('STXingkai')`),'封面不是手写字体');
    assert(await js(`document.querySelector('.home-month-grid').getBoundingClientRect().bottom<=innerHeight`),'默认窗口日期格被裁切');
    await capture('calendar');
    await input('input[aria-label="选择月份"]','2026-08');
    await waitFor(()=>js(`!!document.querySelector('.six-weeks') && document.querySelector('.home-month-grid').getAttribute('aria-busy')==='false'`),'六行月份不能加载');
    assert(await js(`document.querySelector('.home-month-grid').getBoundingClientRect().bottom<=innerHeight`),'六行月份日期格被裁切');
    await capture('calendar-six-weeks');
    await input('input[aria-label="选择月份"]',date.slice(0,7));
    await waitFor(()=>js(`document.querySelector('.home-month-grid').textContent.includes('今天给自己一点温柔。')`),'切回月份后封面丢失');
    main.setSize(900,600);await delay(650);
    const narrow=await js(`({width:innerWidth,bodyWidth:document.documentElement.scrollWidth,contentWidth:document.querySelector('.content').clientWidth,contentScroll:document.querySelector('.content').scrollWidth})`);
    assert(narrow.contentScroll<=narrow.contentWidth+1,'小窗口横向溢出');await capture('calendar-narrow');
    await js(`document.querySelector('.home-nav-toggle').click()`);await delay(600);
    assert(await js(`!document.querySelector('.sidebar').inert&&document.querySelector('.sidebar').getBoundingClientRect().left>=0`),'三横杠菜单不能展开导航');await capture('navigation');
    await clickText('.sidebar .nav-item','日程');await waitFor(()=>js(`document.querySelector('.page-title')?.textContent==='日程'`),'无法返回日程');
    await enter();assert(!await js(`!!document.querySelector('.home-gate-card')`),'不设置密码模式重复出现首次提示');
    await clickText('.home-tools button','设置密码');await clickText('.home-access-options button','设置密码解锁后才能看见这片田园。');
    await input('.home-password-fields input','garden-only-test');await input('.home-password-fields label:nth-child(2) input','garden-only-test');
    await clickText('.home-gate-actions .primary-btn','保存设置');await waitFor(()=>js(`!document.querySelector('.home-protection-backdrop')`),'设置密码失败');
    const protectedStatus=await js(`window.coldesk.invoke('home:status')`);assert(protectedStatus.passwordEnabled,'密码没有生效');
    await clickText('.home-tools button','锁定');await waitFor(()=>js(`!!document.querySelector('.home-unlock')`),'锁定无效');
    await input('.home-unlock input','wrong-password');await clickText('.home-unlock .primary-btn','进入 home');await waitFor(()=>js(`!!document.querySelector('.home-form-error')`),'错误密码未被拒绝');
    await input('.home-unlock input','garden-only-test');await clickText('.home-unlock .primary-btn','进入 home');await waitFor(()=>js(`!!document.querySelector('.home-month-grid')`),'正确密码不能解锁');
    await clickText('.home-tools button','密码设置');
    assert(await js(`document.querySelectorAll('.home-access-options button')[1].getAttribute('aria-pressed')==='true'`),'已设置密码时默认选中了取消保护');
    await clickText('.home-gate-actions .primary-btn','保存设置');
    await waitFor(()=>js(`!document.querySelector('.home-protection-backdrop')`),'保持原密码无法保存');
    assert(await js(`window.coldesk.invoke('home:status').then(s=>s.passwordEnabled)`),'保存空的新密码时移除了保护');
    main.setSize(1120,760);nativeTheme.themeSource='dark';await delay(650);await capture('calendar-dark');nativeTheme.themeSource='light';await delay(200);
    // 模拟编辑后立即关闭窗口，必须等待保存再真正关闭。
    await js(`Array.from(document.querySelectorAll('.home-day')).find(b=>b.getAttribute('aria-label').startsWith(${JSON.stringify(date)})).click()`);await waitFor(()=>js(`!!document.querySelector('#home-body')`),'编辑器重开失败');
    await input('#home-body',entry.body+'\n窗口关闭前最后写下的一句话。');
    await waitFor(()=>js(`window.coldesk.invoke('home:status').then(()=>true)`),'IPC 不可用');
    main.close();await waitFor(()=>Promise.resolve(main.isDestroyed()),'窗口未在保存后关闭');
    const widget=BrowserWindow.getAllWindows().find(w=>w.getTitle()==='ColDesk 悬浮窗');
    await widget.webContents.executeJavaScript(`window.coldesk.invoke('widget:openMain')`);
    await waitFor(()=>{main=BrowserWindow.getAllWindows().find(w=>w.getTitle()==='ColDesk');return Promise.resolve(!!main&&!main.webContents.isLoading());},'主窗口不能重开');
    js=code=>main.webContents.executeJavaScript(code);await delay(300);
    assert(await js(`document.querySelector('.page-title')?.textContent==='日程'`),'重开主窗口不是日程');
    fs.writeFileSync(path.join(output,'report.json'),JSON.stringify({ok:true,date,narrow,cover:true,weatherMood:true,password:true,failedSave:true,closeFlush:true,navigation:true},null,2));
    console.log('home 实机检查通过：封面、正文、天气心情、密码、导航与关闭保存');app.quit();
  } catch(error){if(main&&!main.isDestroyed())fs.writeFileSync(path.join(output,'failure.png'),(await main.capturePage()).toPNG());console.error(error);app.exit(1);}
})();
